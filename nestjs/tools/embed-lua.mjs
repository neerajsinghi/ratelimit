// Embeds the shared Lua scripts from ../scripts into src/lua.generated.ts.
//
// The scripts in the repository's top-level scripts/ directory are the single
// source of truth for both the Go module (which uses go:embed) and this
// package. This step runs automatically before `npm run build` and `npm test`,
// so the published package is self-contained and never drifts from Go.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const scripts = { GCRA_LUA: 'gcra.lua', SLIDING_WINDOW_LUA: 'sliding_window.lua' };

let out = '// Code generated by tools/embed-lua.mjs from ../scripts. DO NOT EDIT.\n';
for (const [name, file] of Object.entries(scripts)) {
  const src = readFileSync(join(root, '..', 'scripts', file), 'utf8');
  out += `\n/** Contents of scripts/${file}. */\nexport const ${name} = ${JSON.stringify(src)};\n`;
}
writeFileSync(join(root, 'src', 'lua.generated.ts'), out);
