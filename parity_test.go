package ratelimit

import (
	"context"
	"encoding/json"
	"flag"
	"math/rand"
	"os"
	"path/filepath"
	"testing"
	"time"
)

// The vectors in testdata/vectors.json pin the exact behaviour of both
// algorithms. They are checked against the in-memory and Redis
// implementations here, and against the NestJS package's implementations in
// nestjs/test/parity.spec.ts, which is what guarantees identical semantics
// across languages. Regenerate with: go test -run TestParity -update
var update = flag.Bool("update", false, "regenerate testdata/vectors.json")

const vectorsPath = "testdata/vectors.json"

type vectorFile struct {
	Comment string       `json:"comment"`
	Cases   []vectorCase `json:"cases"`
}

type vectorCase struct {
	Name      string       `json:"name"`
	Algorithm string       `json:"algorithm"`
	Limit     int          `json:"limit"`
	PeriodUS  int64        `json:"period_us"`
	Steps     []vectorStep `json:"steps"`
}

type vectorStep struct {
	Key          string `json:"key"`
	NowUS        int64  `json:"now_us"`
	Cost         int    `json:"cost"`
	Allowed      bool   `json:"allowed"`
	Remaining    int    `json:"remaining"`
	RetryAfterUS int64  `json:"retry_after_us"`
	ResetAfterUS int64  `json:"reset_after_us"`
}

func algorithmByName(name string) Algorithm {
	if name == SlidingWindow.String() {
		return SlidingWindow
	}
	return GCRA
}

// generateVectors produces pseudo-random request sequences and records the
// in-memory limiter's answers.
func generateVectors(t *testing.T) vectorFile {
	configs := []struct {
		algo   Algorithm
		limit  Limit
		maxGap time.Duration
	}{
		{GCRA, PerSecond(5), 400 * time.Millisecond},
		{GCRA, Limit{3, time.Second}, 500 * time.Millisecond}, // fractional interval
		{GCRA, PerMinute(100), 2 * time.Second},
		{SlidingWindow, PerSecond(5), 400 * time.Millisecond},
		{SlidingWindow, Limit{7, 3 * time.Second}, time.Second},
		{SlidingWindow, PerMinute(100), 2 * time.Second},
	}
	rng := rand.New(rand.NewSource(42))
	f := vectorFile{Comment: "Generated by `go test -run TestParity -update`. Shared by the Go and NestJS test suites."}
	for _, c := range configs {
		now := time.Unix(1_700_000_000, 0).Add(time.Duration(rng.Int63n(int64(time.Second)))).Truncate(time.Microsecond)
		clock := func() time.Time { return now }
		lim := NewMemory(c.limit, WithAlgorithm(c.algo), WithClock(clock))
		vc := vectorCase{
			Name:      c.algo.String() + " " + c.limit.String(),
			Algorithm: c.algo.String(),
			Limit:     c.limit.Requests,
			PeriodUS:  c.limit.Period.Microseconds(),
		}
		for i := 0; i < 80; i++ {
			if rng.Intn(3) > 0 { // many requests share a timestamp
				now = now.Add(time.Duration(rng.Int63n(int64(c.maxGap)))).Truncate(time.Microsecond)
			}
			key := []string{"a", "b"}[rng.Intn(2)]
			cost := 1
			switch rng.Intn(6) {
			case 0:
				cost = 0
			case 1:
				cost = 1 + rng.Intn(c.limit.Requests)
			}
			res, err := lim.Allow(context.Background(), key, cost)
			if err != nil {
				t.Fatal(err)
			}
			vc.Steps = append(vc.Steps, vectorStep{
				Key: key, NowUS: now.UnixMicro(), Cost: cost,
				Allowed: res.Allowed, Remaining: res.Remaining,
				RetryAfterUS: res.RetryAfter.Microseconds(), ResetAfterUS: res.ResetAfter.Microseconds(),
			})
		}
		f.Cases = append(f.Cases, vc)
	}
	return f
}

func TestParity(t *testing.T) {
	if *update {
		b, err := json.MarshalIndent(generateVectors(t), "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.FromSlash(vectorsPath), append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(filepath.FromSlash(vectorsPath))
	if err != nil {
		t.Fatal(err)
	}
	var f vectorFile
	if err := json.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	if len(f.Cases) == 0 {
		t.Fatal("no vectors")
	}
	for _, vc := range f.Cases {
		var now int64
		clock := func() time.Time { return time.UnixMicro(now) }
		l := Limit{Requests: vc.Limit, Period: time.Duration(vc.PeriodUS) * time.Microsecond}
		opts := []Option{WithAlgorithm(algorithmByName(vc.Algorithm)), WithClock(clock)}
		for name, lim := range backends(t, l, opts...) {
			t.Run(vc.Name+"/"+name, func(t *testing.T) {
				for i, s := range vc.Steps {
					now = s.NowUS
					res, err := lim.Allow(context.Background(), s.Key, s.Cost)
					if err != nil {
						t.Fatal(err)
					}
					got := vectorStep{
						Key: s.Key, NowUS: s.NowUS, Cost: s.Cost,
						Allowed: res.Allowed, Remaining: res.Remaining,
						RetryAfterUS: res.RetryAfter.Microseconds(), ResetAfterUS: res.ResetAfter.Microseconds(),
					}
					if got != s {
						t.Fatalf("step %d:\n got %+v\nwant %+v", i, got, s)
					}
				}
			})
		}
	}
}
